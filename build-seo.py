#!/usr/bin/env python3
"""
SEO head tags + sitemap.xml + robots.txt for the top-level pages.

For every  *.html  in this folder it reads the page's own <title> and
<meta name="description">, and writes a generated block right after the
description (between  <!-- seo:start -->  and  <!-- seo:end -->):
  canonical URL, favicon, Open Graph + Twitter share tags, JSON-LD
  (Organization, WebSite, WebPage, BreadcrumbList), and  noindex  for drafts.

It also writes  sitemap.xml  (indexable pages + the pre-rendered glossary
terms, with lastmod from git) and  robots.txt.

To change a page's title or description, edit the <title>/<meta> in the page,
then rerun — the block is regenerated, never hand-edited.

Run from the deploy/ folder:   python3 build-seo.py
Zero dependencies (standard library only).
"""
import os, re, html, glob, json, subprocess, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
SITE_BASE = "https://involve.asia"
SITE_NAME = "Involve Asia"
LEGAL_NAME = "Involve Asia Technologies Sdn Bhd"
TWITTER = "@InvolveAsia"
SAME_AS = [
    "https://www.facebook.com/involveasia",
    "https://www.instagram.com/involveasia/",
    "https://www.linkedin.com/company/involve-asia/",
    "https://twitter.com/InvolveAsia",
]
# Share image (1200×630) — supplied by design; tags point here until it lands.
OG_IMAGE = "media/brand/og-default.png"
OG_IMAGE_ALT = "Involve Asia — the affiliate marketing platform for Asia"
LOGO = "media/brand/logo-512.png"

# Draft / internal pages: reachable for review, but noindex and kept out of the sitemap.
def is_draft(name):
    return name.endswith("-v2.html") or name == "traffic-validation.html"

START, END = "<!-- seo:start", "<!-- seo:end -->"


def page_url(name):
    return SITE_BASE + "/" if name == "index.html" else f"{SITE_BASE}/{name}"


def attr(s):
    return html.escape(s, quote=True)


def page_name(title):
    # "For advertisers | Involve Asia" -> "For advertisers"
    return re.split(r"\s+[|—–]\s+", title)[0].strip() or title


def json_ld(name, title, desc, url):
    org = {"@type": "Organization", "@id": SITE_BASE + "/#organization", "name": SITE_NAME,
           "legalName": LEGAL_NAME, "url": SITE_BASE + "/",
           "logo": {"@type": "ImageObject", "url": f"{SITE_BASE}/{LOGO}", "width": 512, "height": 512},
           "sameAs": SAME_AS}
    site = {"@type": "WebSite", "@id": SITE_BASE + "/#website", "name": SITE_NAME,
            "url": SITE_BASE + "/", "publisher": {"@id": SITE_BASE + "/#organization"}, "inLanguage": "en"}
    page = {"@type": "WebPage", "@id": url + "#webpage", "url": url, "name": title,
            "description": desc, "isPartOf": {"@id": SITE_BASE + "/#website"},
            "about": {"@id": SITE_BASE + "/#organization"}, "inLanguage": "en"}
    graph = [org, site, page]
    if name != "index.html":
        crumbs = {"@type": "BreadcrumbList", "@id": url + "#breadcrumb", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Home", "item": SITE_BASE + "/"},
            {"@type": "ListItem", "position": 2, "name": page_name(title), "item": url}]}
        page["breadcrumb"] = {"@id": url + "#breadcrumb"}
        graph.append(crumbs)
    body = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False, indent=1)
    return '<script type="application/ld+json">\n' + body.replace("</", "<\\/") + "\n</script>"


def seo_block(name, title, desc):
    url = page_url(name)
    draft = is_draft(name)
    img = f"{SITE_BASE}/{OG_IMAGE}"
    lines = [
        f"{START} (generated by build-seo.py — edit <title>/<meta description> above, then rerun) -->",
        f'<link rel="canonical" href="{attr(url)}" />',
    ]
    if draft:
        lines.append('<meta name="robots" content="noindex, follow" />')
    lines += [
        '<link rel="icon" type="image/png" sizes="32x32" href="media/brand/favicon-32.png" />',
        '<link rel="apple-touch-icon" sizes="180x180" href="media/brand/apple-touch-icon.png" />',
        '<meta property="og:type" content="website" />',
        f'<meta property="og:site_name" content="{SITE_NAME}" />',
        f'<meta property="og:title" content="{attr(title)}" />',
        f'<meta property="og:description" content="{attr(desc)}" />',
        f'<meta property="og:url" content="{attr(url)}" />',
        f'<meta property="og:image" content="{attr(img)}" />',
        '<meta property="og:image:width" content="1200" />',
        '<meta property="og:image:height" content="630" />',
        f'<meta property="og:image:alt" content="{attr(OG_IMAGE_ALT)}" />',
        '<meta name="twitter:card" content="summary_large_image" />',
        f'<meta name="twitter:site" content="{TWITTER}" />',
        f'<meta name="twitter:title" content="{attr(title)}" />',
        f'<meta name="twitter:description" content="{attr(desc)}" />',
        f'<meta name="twitter:image" content="{attr(img)}" />',
    ]
    if not draft:
        lines.append(json_ld(name, title, desc, url))
    lines.append(END)
    return "\n".join(lines)


def git_date(paths):
    """Latest commit date (YYYY-MM-DD) touching any of paths; today if uncommitted/changed."""
    try:
        dirty = subprocess.run(["git", "status", "--porcelain", "--", *paths], cwd=HERE,
                               capture_output=True, text=True).stdout.strip()
        if dirty:
            return datetime.date.today().isoformat()
        out = subprocess.run(["git", "log", "-1", "--format=%cs", "--", *paths], cwd=HERE,
                             capture_output=True, text=True).stdout.strip()
        return out or datetime.date.today().isoformat()
    except OSError:
        return datetime.date.today().isoformat()


def main():
    sitemap = []
    for path in sorted(glob.glob(os.path.join(HERE, "*.html"))):
        name = os.path.basename(path)
        src = open(path, encoding="utf-8").read()
        m_title = re.search(r"<title>(.*?)</title>", src, re.S)
        if not m_title:
            print(f"skip   {name} (no <title>)")
            continue
        title = html.unescape(m_title.group(1).strip())
        m_desc = re.search(r'<meta name="description" content="([^"]*)"\s*/?>', src)
        desc = html.unescape(m_desc.group(1)) if m_desc else ""
        if not desc and not is_draft(name):
            print(f"WARN   {name} has no meta description")

        # Drop any previous generated block, then insert after the description (or the title).
        src = re.sub(re.escape(START) + r".*?" + re.escape(END) + r"\n?", "", src, flags=re.S)
        anchor = m_desc.group(0) if m_desc else m_title.group(0)
        at = src.index(anchor) + len(anchor)
        src = src[:at] + "\n" + seo_block(name, title, desc) + src[at:]
        open(path, "w", encoding="utf-8").write(src)

        if not is_draft(name):
            jsx = re.findall(r'<script type="text/babel" src="([^"]+)"', src)
            sitemap.append((page_url(name), git_date([name, *jsx])))
        print(f"{'draft ' if is_draft(name) else 'ok    '} {name}")

    # Pre-rendered glossary terms (built by build-glossary.py) — skip any marked noindex.
    for path in sorted(glob.glob(os.path.join(HERE, "glossary-term", "*", "index.html"))):
        if "noindex" in open(path, encoding="utf-8").read(4000):
            continue
        slug = os.path.basename(os.path.dirname(path))
        rel = os.path.relpath(path, HERE)
        sitemap.append((f"{SITE_BASE}/glossary-term/{slug}/", git_date([rel])))

    xml = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for loc, lastmod in sitemap:
        xml.append(f"  <url><loc>{html.escape(loc)}</loc><lastmod>{lastmod}</lastmod></url>")
    xml.append("</urlset>")
    open(os.path.join(HERE, "sitemap.xml"), "w", encoding="utf-8").write("\n".join(xml) + "\n")

    open(os.path.join(HERE, "robots.txt"), "w", encoding="utf-8").write(
        "User-agent: *\nAllow: /\n\n" f"Sitemap: {SITE_BASE}/sitemap.xml\n")
    print(f"\nsitemap.xml: {len(sitemap)} URLs · robots.txt written")


if __name__ == "__main__":
    main()
